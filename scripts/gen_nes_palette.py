#!/usr/bin/env python3
"""Generate hw/rtl/nes_pal_rom.v from the LaiNES palette table.

The 64 NES colours are converted to RGB565 with the same shifts the software
frontend uses (sw/nes/src/gui.cpp), so hardware and software agree bit for bit.

usage: gen_nes_palette.py [palette.inc] [out.v]
"""
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "sw/nes/vendor/laines/src/palette.inc"
dst = sys.argv[2] if len(sys.argv) > 2 else "hw/rtl/nes_pal_rom.v"

text = open(src).read()
# The first table is basePalette[64]; stop before any emphasis table.
body = text.split("};", 1)[0]
colours = [int(m, 16) for m in re.findall(r"0x([0-9A-Fa-f]+)", body)]
if len(colours) != 64:
    sys.exit("expected 64 colours in %s, found %d" % (src, len(colours)))


def rgb565(p):
    p &= 0xFFFFFF
    return ((p >> 8) & 0xF800) | ((p >> 5) & 0x07E0) | ((p >> 3) & 0x001F)


out = []
out.append("// Generated by scripts/gen_nes_palette.py from the LaiNES basePalette.")
out.append("// Do not edit by hand. NES colour index -> RGB565.")
out.append("`timescale 1ns/1ps")
out.append("")
out.append("module nes_pal_rom (")
out.append("    input  wire [5:0]  idx,")
out.append("    output reg  [15:0] rgb")
out.append(");")
out.append("    always @* begin")
out.append("        case (idx)")
for i, c in enumerate(colours):
    out.append("            6'd%d: rgb = 16'h%04X;" % (i, rgb565(c)))
out.append("            default: rgb = 16'h0000;")
out.append("        endcase")
out.append("    end")
out.append("endmodule")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote %s (%d colours)" % (dst, len(colours)))
